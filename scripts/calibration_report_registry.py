"""Fail-closed lifecycle for private AI-calibration metrics.

A reviewed label can later be withdrawn, changed, or deleted. Reports based
on that revoked review must not remain in the ACTIVE reporting directory as
though they were still current. This module archives only confidently
recognized reports generated by the VRC Club Charts calibration tool.
Never deletes user footage, original labels, draft AI reports, or unknown files.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path

METRIC_NAME = re.compile(r"calibration-metrics-([0-9a-f]{12})\.json")
MAX_FILE_BYTES = 1_000_000


def model_key(model: str) -> str:
    if not isinstance(model, str) or not model.startswith("gemini-"):
        raise ValueError("Unrecognized calibration model")
    return hashlib.sha256(model.encode("utf-8")).hexdigest()[:12]


def _recognized_report(path: Path, key: str) -> bool:
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_FILE_BYTES:
        return False
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError):
        return False
    return (
        isinstance(data, dict)
        and data.get("schemaVersion") == 1
        and data.get("status") == "local-operator-labeled-calibration"
        and isinstance(data.get("reviewedClips"), int)
        and data.get("reviewedClips") >= 1
        and data.get("readyForUnattendedDeployment") is False
        and data.get("equipmentFunctionalityVerified") is False
        and isinstance(data.get("model"), str)
        and model_key(data["model"]) == key
    )


def _recognized_dataset(path: Path) -> bool:
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_FILE_BYTES:
        return False
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError):
        return False
    return (
        isinstance(data, dict) and data.get("schemaVersion") == 1
        and isinstance(data.get("cases"), list)
        and len(data["cases"]) <= 200
    )


def _archive(path: Path, history: Path) -> None:
    if history.is_symlink():
        raise ValueError("Calibration history folder cannot be a symlink")
    history.mkdir(parents=True, exist_ok=True)
    signature = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    destination = history / (path.stem + "-" + signature + ".json")
    if destination.exists():
        if destination.is_symlink() or destination.read_bytes() != path.read_bytes():
            raise FileExistsError("Conflicting calibration history snapshot: " + destination.name)
        path.unlink()  # identical backup already exists
        return
    path.rename(destination)  # atomic within local workspace volume


def archive_inactive_reports(work_dir: Path, active_model_keys: set[str]) -> dict:
    """Move stale active metrics to private history; preserve unknown files."""
    if not work_dir.is_dir():
        return {"archived": 0, "ignoredUnknown": 0}
    if work_dir.is_symlink():
        raise ValueError("Calibration workspace must not be a symlink")
    history = work_dir / "history"
    to_archive = []
    unknown = 0
    for path in sorted(work_dir.glob("calibration-metrics-*.json")):
        match = METRIC_NAME.fullmatch(path.name)
        if not match or match.group(1) in active_model_keys:
            continue
        key = match.group(1)
        if not _recognized_report(path, key):
            unknown += 1
            continue
        to_archive.append(path)
        dataset = work_dir / ("reviewed-dataset-" + key + ".json")
        if dataset.exists():
            if _recognized_dataset(dataset):
                to_archive.append(dataset)
            else:
                unknown += 1
    for path in to_archive:
        _archive(path, history)
    return {"archived": len([x for x in to_archive if METRIC_NAME.fullmatch(x.name)]),
            "ignoredUnknown": unknown}
